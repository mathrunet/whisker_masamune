package net.mathru.whisker.admob

/** Lifecycle regression tests that run on the JVM without extra test dependencies. */
fun main() {
    val state = BannerLifecycle()
    check(state.configure("test-ad-unit", 360))
    check(state.beginLoad() == null)
    state.attach()
    val first = checkNotNull(state.beginLoad())
    check(state.beginLoad() == null)
    check(state.loaded(first))
    state.detach()
    check(!state.isCurrent(first))
    check(state.beginLoad() == null)
    check(!state.configure("test-ad-unit", 360))
    state.attach()
    val reattached = checkNotNull(state.beginLoad())
    check(reattached != first)
    check(!state.loaded(first))
    check(state.failed(reattached) == 5_000L)
    check(state.failed(reattached) == null)
    var token = checkNotNull(state.beginLoad())
    check(state.failed(token) == 10_000L)
    token = checkNotNull(state.beginLoad())
    check(state.failed(token) == 20_000L)
    token = checkNotNull(state.beginLoad())
    check(state.failed(token) == null)
    state.detach()
    check(!state.isCurrent(token))
    state.attach()
    token = checkNotNull(state.beginLoad())
    check(state.loaded(token))
    // Retries still work when the SDK's auto-refresh fails after a successful display.
    check(state.failed(token) == 5_000L)
    check(state.failed(token) == null)
    check(state.configure(widthDp = 320))
    check(!state.isCurrent(token))
    token = checkNotNull(state.beginLoad())
    check(state.failed(token) == 5_000L)
    println("BannerLifecycle: all regression checks passed")
}
